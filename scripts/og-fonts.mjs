import { readFileSync, writeFileSync } from "node:fs";

/**
 * Writes lib/og/fonts.ts: the brand fonts as base64, for the link-preview images (next/og).
 * Satori reads TTF, OTF and WOFF, not WOFF2, and the image routes have to run on the Cloudflare
 * Worker, where there is no file system to read them from, so the bytes are bundled into the code.
 *
 * - Inter 400 and 600: the WOFF files in @fontsource/inter.
 * - Bricolage Grotesque 600: @fontsource-variable only ships variable WOFF2, so
 *   lib/og/fonts/bricolage-grotesque-600.woff is a static instance of it at weight 600, made once
 *   with fontTools (pip install fonttools brotli):
 *     from fontTools.ttLib import TTFont; from fontTools.varLib import instancer
 *     f = instancer.instantiateVariableFont(TTFont(
 *       "node_modules/@fontsource-variable/bricolage-grotesque/files/bricolage-grotesque-latin-wght-normal.woff2"), {"wght": 600})
 *     f.flavor = "woff"; f.save("lib/og/fonts/bricolage-grotesque-600.woff")
 *
 * Run from the repo root: node scripts/og-fonts.mjs
 */
const b64 = (p) => readFileSync(p).toString("base64");
const inter = (w) => b64(`node_modules/@fontsource/inter/files/inter-latin-${w}-normal.woff`);

const out = `// Generated by scripts/og-fonts.mjs. Do not edit.
export const INTER_400 = "${inter(400)}";
export const INTER_600 = "${inter(600)}";
export const BRICOLAGE_600 = "${b64("lib/og/fonts/bricolage-grotesque-600.woff")}";
`;
writeFileSync("lib/og/fonts.ts", out);
console.log("wrote lib/og/fonts.ts");
